"""Project diagnostics and handover reports. Checks only read; nothing is fixed silently."""
from __future__ import annotations

import os
import shutil
import sqlite3
from datetime import datetime
from pathlib import Path
from typing import Any

from stackloom import envfiles, gitops, maps, paths, runtime
from stackloom.security import redact


def _check(name: str, ok: bool | None, detail: str, fix: str = "") -> dict[str, Any]:
    return {"check": name, "status": "ok" if ok else "unknown" if ok is None else "problem", "detail": detail, "fix": fix}


def diagnose(conn: sqlite3.Connection, project: dict[str, Any]) -> list[dict[str, Any]]:
    root = Path(project["path"])
    out = [_check("Folder", root.is_dir(), str(root) if root.is_dir() else "The project folder is missing.",
                  "Move it back, or unregister the project.")]
    if not root.is_dir():
        return out
    if (root / "package.json").exists():
        out.append(_check("Node dependencies", (root / "node_modules").is_dir(),
                          "node_modules present" if (root / "node_modules").is_dir() else "node_modules is missing",
                          "Run `pnpm install` (or npm install) in the project."))
    if (root / "pyproject.toml").exists() or (root / "requirements.txt").exists():
        venv = next((v for v in (".venv", "venv") if (root / v / "bin" / "python").exists()), None)
        out.append(_check("Python environment", bool(venv) or None, f"{venv} present" if venv else "No .venv found in the project",
                          "Create one with `uv venv && uv pip install -e .` (or -r requirements.txt)."))
    for gap in envfiles.missing(str(root)):
        out.append(_check(f"Env file {gap['file']}", False,
                          ("The file does not exist; the example lists " if gap["missing_file"] else "Missing or empty: ")
                          + ", ".join(gap["keys"][:12]) + ("…" if len(gap["keys"]) > 12 else ""),
                          "Copy the example and fill in the values."))
    launch = project.get("launch")
    if launch:
        try:
            for step in runtime.start_commands(conn, project, rendered=False):
                exe = step["command"][0]
                found = shutil.which(exe) if "/" not in exe else Path(step["cwd"], exe).exists() or Path(exe).exists()
                out.append(_check(f"Start command ({step['name']})", bool(found), " ".join(step["command"]),
                                  "" if found else f"{exe} was not found. Install it or fix the command."))
        except runtime.Refused as exc:
            out.append(_check("Start command", False, str(exc)))
        if runtime.compose_spec(project):
            ok = runtime.docker_available()
            out.append(_check("Docker", ok, "The engine answers." if ok else "Docker is not running.", "Start Docker Desktop."))
        clash = []
        if runtime.status(conn, project)["state"] not in ("running", "partial", "external"):
            clash = runtime.conflicts(conn, project)
        out.append(_check("Ports", not clash, "; ".join(clash) or "No conflicts.", "Stop the other program or pick another port."))
        out.append(_check("Start approval", runtime.approved(conn, project) or None,
                          "Approved." if runtime.approved(conn, project) else "Not approved yet (asked at the first start).", ""))
    git = gitops.summary(root)
    if git.get("repo"):
        problems = []
        if git.get("conflicts"):
            problems.append(f"{git['conflicts']} conflicted files")
        if git.get("operation"):
            problems.append(f"a {git['operation']} is in progress")
        if not git.get("remotes"):
            problems.append("no remote")
        out.append(_check("Git", not problems, ", ".join(problems) or f"{git['branch']}, {git['changed']} changed",
                          "Resolve them on the Git page." if problems else ""))
    else:
        out.append(_check("Git", None, "Not a Git repository."))
    record = maps.get(conn, project["id"])
    out.append(_check("Project map", record["status"] == "ready" or None,
                      {"ready": f"{record['stats'].get('nodes', 0)} symbols", "none": "No map yet"}.get(record["status"], record["status"]),
                      "" if record["status"] == "ready" else "Build it on the project page."))
    return out


def handover(conn: sqlite3.Connection, project: dict[str, Any]) -> tuple[str, Path]:
    """A Markdown handover report, secrets removed. Saved under ~/.stackloom/reports."""
    root = Path(project["path"])
    lines = [f"# Handover: {project.get('name', project['id'])}", "",
             f"Generated by STACKLOOM on {datetime.now().strftime('%d %b %Y %H:%M')}.", "",
             "## Summary", "", f"- Path: `{root}`", f"- Group: {project['group']}", f"- Kind: {project.get('kind', '-')}",
             f"- Stack: {', '.join(project.get('stack') or ([project['runtime']] if project.get('runtime') else [])) or 'not detected'}"]
    if project.get("notes"):
        lines.append(f"- Notes: {project['notes']}")
    if project.get("components"):
        lines += ["", "## Components", ""] + [f"- `{c['name']}/`: {', '.join(c['stack']) or '-'}" for c in project["components"]]
    lines += ["", "## How to start it", ""]
    if project.get("launch"):
        try:
            for step in runtime.start_commands(conn, project, rendered=False):
                lines.append(f"- {step['name']}: `{' '.join(step['command'])}` (in `{step['cwd']}`)")
        except runtime.Refused as exc:
            lines.append(f"- {exc}")
        lines.append(f"- Launch from STACKLOOM: {'enabled' if project.get('safe_to_launch') else 'disabled'}")
    else:
        lines.append("No start command is registered.")
    services = runtime.resolved_services(conn, project)
    if services:
        lines += ["", "## Services and ports", "", "| Service | Port | URL |", "|---|---|---|"]
        lines += [f"| {s['name']} | {s['port'] or 'assigned at start'}{' (pinned)' if s.get('pinned') else ''} | {s.get('url') or '-'} |"
                  for s in services]
    env_files = [f for f in envfiles.files(str(root)) if f["type"] == "env"]
    if env_files:
        lines += ["", "## Environment (names only)", ""]
        for f in env_files:
            data = envfiles.read(str(root), f["path"])
            lines.append(f"- `{f['path']}`: " + ", ".join(k["key"] + ("" if k["set"] else " (empty)") for k in data["keys"]))
    git = gitops.summary(root)
    if git.get("repo"):
        lines += ["", "## Git", "", f"- Branch: {git['branch']}, {git['changed']} uncommitted changes",
                  f"- Remotes: {', '.join(r['url'] for r in git['remotes']) or 'none'}"]
        repo = Path(git["repo"])
        lines += ["- Recent commits:"] + [f"  - {c['date'][:10]} {c['short']} {c['subject']}" for c in gitops.log(repo, 10)]
    record = maps.get(conn, project["id"])
    lines += ["", "## Code map", "", f"- CodeCortex map: {record['status']}"
              + (f", {record['stats'].get('nodes')} symbols in {record['stats'].get('files')} files" if record["status"] == "ready" else ""),
              "- Ask it: `codecortex query --query \"<question>\"` in the project folder."]
    lines += ["", "## Checks", ""] + [f"- {'OK' if c['status'] == 'ok' else 'Check' if c['status'] == 'unknown' else 'Problem'}: "
                                      f"{c['check']}: {c['detail']}" for c in diagnose(conn, project)]
    for doc in project.get("docs") or []:
        lines.append(f"- Read: `{doc}`")
    text = redact("\n".join(lines) + "\n")
    out_dir = paths.home() / "reports"
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"handover-{project['id']}-{datetime.now().strftime('%Y%m%d-%H%M%S')}.md"
    path.write_text(text, encoding="utf-8")
    os.chmod(path, 0o600)
    return text, path
